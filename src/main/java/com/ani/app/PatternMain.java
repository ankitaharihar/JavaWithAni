package com.ani.app;

public class PatternMain {
	public static void main(String[] args) {
		for(int i = 0; i < 2 ; i ++) {
			System.out.println("# "+ "# "+ "# " + "# " + "# ");
		}
		
		
		for(int i = 0; i < 2 ; i ++) {
			System.out.println("@ " + "@ "+ "@ " +"* " + "* ");
		}
		 
		
		for(int i = 0; i < 2 ; i ++) {
			System.out.println("! " + "! "+ "* " +"* " + "* ");
		}
	}

}
